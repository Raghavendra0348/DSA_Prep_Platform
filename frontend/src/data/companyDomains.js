/**
 * Get the domain for a company by its slug.
 * Falls back to guessing: slug → slug.com (replacing hyphens).
 */
export function getCompanyDomain(slug) {
  if (DOMAIN_OVERRIDES[slug]) return DOMAIN_OVERRIDES[slug];
  return slug.replace(/-/g, '') + '.com';
}

export function getLogoUrl(slug, size = 128) {
  const domain = getCompanyDomain(slug);
  return `https://t2.gstatic.com/faviconV2?client=SOCIAL&type=FAVICON&fallback_opts=TYPE,SIZE,URL&url=http://${domain}&size=128`;
}

