export function getTopicCategory(slug) {
  const clean = (slug || '').toLowerCase().replace(/\s+/g, '-');
  return CATEGORY_MAPPINGS[clean] || CATEGORY_MAPPINGS[slug?.toLowerCase()] || 'other';
}
